import { test, expect } from '@playwright/test'

test('login gate, scan CRUD, pagination and credential library',async({page})=>{
  test.skip(!process.env.SMOKE_USERNAME||!process.env.SMOKE_PASSWORD,'Set credentials for a local test account')
  await page.goto('/scans')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Username',{exact:true}).fill(process.env.SMOKE_USERNAME!)
  await page.getByLabel('Password',{exact:true}).fill(process.env.SMOKE_PASSWORD!)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Scans.'})).toBeVisible()
  const name=`Smoke lab ${Date.now()}`
  await page.getByRole('link',{name:'+ New scan'}).click()
  await page.getByLabel('Scan name').fill(name)
  await page.getByLabel('Authorized IP addresses / CIDRs').fill('192.0.2.1')
  await page.getByLabel('TCP ports').fill('80')
  await page.getByRole('button',{name:'Save scan',exact:true}).click()
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Scans',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Scans.'})).toBeVisible()
  await page.getByRole('searchbox').fill(name)
  await page.getByRole('button',{name:'Search',exact:true}).click()
  await expect(page.getByText('1 items · Page 1 of 1')).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Delete',exact:true}).click()
  await expect(page.getByText('No results found.')).toBeVisible()
  await page.getByRole('link',{name:'Credentials',exact:true}).click()
  await page.getByRole('button',{name:'+ Add credential'}).click()
  await page.getByLabel('Label',{exact:true}).fill(name)
  await page.getByLabel('Username',{exact:true}).fill('approved-user')
  await page.getByLabel('Password',{exact:true}).fill('local-fixture-only')
  await page.getByRole('button',{name:'Save credential'}).click()
  await expect(page.getByText('Credential saved')).toBeVisible()
  const row=page.getByRole('row').filter({hasText:name})
  await expect(row).not.toContainText('local-fixture-only')
  page.once('dialog',dialog=>dialog.accept())
  await row.getByRole('button',{name:'Delete',exact:true}).click()
  await expect(page.getByText('Credential deleted')).toBeVisible()
  await page.getByRole('button',{name:'Sign out'}).click()
  await expect(page).toHaveURL(/\/login$/)
})

