test('URL-only scan can be saved, edited and deleted with blank IP targets',async({page})=>{
  test.skip(!process.env.SMOKE_USERNAME||!process.env.SMOKE_PASSWORD,'Set a local test account')
  await page.goto('/login')
  await page.getByLabel('Username',{exact:true}).fill(process.env.SMOKE_USERNAME!)
  await page.getByLabel('Password',{exact:true}).fill(process.env.SMOKE_PASSWORD!)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page).toHaveURL(/\/scans$/)
  const name=`URL-only browser ${Date.now()}`
  await page.getByRole('link',{name:'+ New scan'}).click()
  await page.getByLabel('Scan name').fill(name)
  await page.getByRole('button',{name:'Save scan',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Provide at least one IP/CIDR target, hostname or HTTP(S) URL')
  await page.getByLabel('Hostnames or HTTP(S) URLs').fill('http://192.0.2.1:8080/')
  await page.getByRole('button',{name:'Save scan',exact:true}).click()
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
  await page.getByRole('link',{name:'Edit configuration'}).click()
  await expect(page.getByLabel('Authorized IP addresses / CIDRs')).toHaveValue('')
  await expect(page.getByLabel('Hostnames or HTTP(S) URLs')).toHaveValue('http://192.0.2.1:8080/')
  await page.getByRole('link',{name:'Back to scans'}).click()
  await expect(page.getByRole('heading',{name:'Scans.'})).toBeVisible()
  await page.getByRole('searchbox').fill(name)
  await page.getByRole('button',{name:'Search',exact:true}).click()
  await expect(page.getByText('1 items · Page 1 of 1')).toBeVisible()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Delete',exact:true}).click()
  await expect(page.getByText('No results found.')).toBeVisible()
})
